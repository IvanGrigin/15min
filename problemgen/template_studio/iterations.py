"""Повторяющиеся операции: сколько шагов до цели.

Два семейства задач корпуса устроены одинаково — правило применяют снова
и снова, пока не наступит условие, — и оба невыразимы формулой.

**Сиракузская последовательность.** «На доске написано число. Раз в минуту,
если оно чётное, его делят пополам, а если нечётное — умножают на три
и прибавляют единицу. Через сколько минут на доске появится единица?»
Короткой формулы для числа шагов нет и, насколько известно, быть не может:
считать приходится честно, шаг за шагом.

**Эпидемия.** «В школе, где учатся 655 детей, каждый день заболевает больше
половины ещё не заболевших. На какой день можно утверждать, что заболели
все?» Худший случай — заболевает ровно столько, сколько нужно, чтобы
здоровых осталось как можно больше: их становится (n − 1) // 2. Отсюда
и считается число дней.
"""
from __future__ import annotations

MAX_STEPS = 1000
MAX_START = 1_000_000


class IterationError(ValueError):
    """Процесс нельзя разыграть или он не заканчивается за разумное время."""


def _check_start(value: object) -> int:
    if not isinstance(value, int) or isinstance(value, bool) or value < 1:
        raise IterationError(f"Начальное число должно быть натуральным, получено {value!r}.")
    if value > MAX_START:
        raise IterationError(f"Начальное число больше предела {MAX_START}.")
    return value


def collatz_steps(start: int) -> int:
    """Сколько шагов нужно, чтобы дойти до единицы.

    Чётное делится пополам, нечётное умножается на три и прибавляет один.
    Единица считается достигнутой целью, а не шагом.
    """
    value = _check_start(start)
    steps = 0
    while value != 1:
        value = value // 2 if value % 2 == 0 else 3 * value + 1
        steps += 1
        if steps > MAX_STEPS:
            raise IterationError(f"Из {start} за {MAX_STEPS} шагов до единицы не дошли.")
    return steps


def collatz_peak(start: int) -> int:
    """Наибольшее число, встретившееся по дороге к единице.

    Нужно шаблону, чтобы отбрасывать жеребьёвки, где число вырастает
    до неприличия: ребёнок должен успеть досчитать до конца.
    """
    value = _check_start(start)
    peak = value
    steps = 0
    while value != 1:
        value = value // 2 if value % 2 == 0 else 3 * value + 1
        peak = max(peak, value)
        steps += 1
        if steps > MAX_STEPS:
            raise IterationError(f"Из {start} за {MAX_STEPS} шагов до единицы не дошли.")
    return peak


def halving_days(people: int) -> int:
    """Через сколько дней заболеют все при «больше половины здоровых за день».

    Считается худший случай: каждый день заболевает наименьшее число,
    которое ещё считается «больше половины», поэтому здоровых остаётся
    (n − 1) // 2. Это и есть ответ задачи — день, к которому здоровых
    точно не осталось при любом ходе эпидемии.
    """
    healthy = _check_start(people)
    days = 0
    while healthy > 0:
        healthy = (healthy - 1) // 2
        days += 1
        if days > MAX_STEPS:
            raise IterationError(f"Из {people} здоровых эпидемия не закончилась.")
    return days
